// Rebuild from the factual PEMA snapshot collected during the audit.
// Raw HTML stays private; output contains only vehicle facts and source URLs.
const fs=require('node:fs'),vm=require('node:vm');
const mapping=require('./engine-catalogue-map.cjs');
const input=process.argv[2];
if(!input)throw Error('Usage: node scripts/build-engine-catalogue.cjs <parsed snapshot>');
const data=JSON.parse(fs.readFileSync(input,'utf8'));
const ctx=vm.createContext({});
vm.runInContext(['database','ford-data','catalogue-data'].map(n=>fs.readFileSync('js/'+n+'.js','utf8')).join('\n')+';this.db=VEHICLE_DB',ctx);
const output={},sources={};
const year=s=>s?Number(s.slice(-4)):9999;
const fuel=e=>/BiFuel|LPG/i.test(e.label)?'lpg':/EcoFuel|TGI|CNG|g-tron/i.test(e.label)?'cng':/hybrid|extender/.test(e.group)?'hybrid':/dies/.test(e.group)?'diesel':/elektr/.test(e.group)?'electric':'petrol';
for(const [brand,models]of Object.entries(mapping))for(const [key,config]of Object.entries(models)){
 const model=ctx.db[brand].models[key];if(!model)throw Error('Unknown model '+key);
 const ids=Array.isArray(config)?config:config.ids;
 const pattern=config.pattern?new RegExp(config.pattern,'i'):null;
 const rows=[];
 for(const id of ids){const source=data[id];if(!source)throw Error('Missing source '+id);sources['pema'+id]=['PEMA – '+source.name,'https://pemacz.cz'+source.url];
  for(const e of source.engines){
   if(year(e.from)>model.years[1]||year(e.to)<model.years[0]||pattern&&!pattern.test(e.label))continue;
   // Curated special editions must not inherit unrelated engines from the whole family.
   if(key.includes('_gti')&&!/GTI/i.test(e.label)&&!(key==='golf_4_gti'&&/1\.8 T|2\.3|1\.9 TDI/.test(e.label)))continue;
   if(key==='s4_b9_2019'&&!/^S4/.test(e.label))continue;
   if(key==='sq5_2021'&&!/^SQ5/.test(e.label))continue;
   if(key.includes('phev')&&!/plug-in hybrid/.test(e.group))continue;
   if(key.includes('ecoblue')&&(!/^2\.0/.test(e.label)||fuel(e)!=='diesel'))continue;
   if(key==='tourneo_connect_2'&&(!/^1\.6/.test(e.label)||fuel(e)!=='diesel'))continue;
   if(key==='ranger_t6_fl'&&!/^2\.2|^3\.2/.test(e.label))continue;
   if(key==='mustang_6'&&![233,310].includes(e.power))continue;
   rows.push({name:e.label+' '+e.power+' kW',power:e.power,fuel:fuel(e),codes:e.codes,from:e.from,to:e.to,source:'pema'+id,vehicleId:e.id,body:source.name});
  }
 }
 if(!rows.length)throw Error('No applicable rows '+brand+'/'+key);
 output[brand+'/'+key]={rows,motorcycle:['honda','yamaha'].includes(brand)};
}
fs.writeFileSync('js/engine-catalogue-data.js','/* Factual catalogue snapshot, PEMA 2026-10-25. Generated by scripts/build-engine-catalogue.cjs.\n * Catalogue coverage includes different markets; not a VIN lookup or a claim of Czech availability. */\nconst ENGINE_CATALOGUE_SOURCES = '+JSON.stringify(sources,null,2)+';\nconst ENGINE_CATALOGUE_DATA = '+JSON.stringify(output)+';\n');
console.log(Object.keys(output).length+' mapped models; '+Object.keys(sources).length+' source pages; '+Object.values(output).reduce((n,m)=>n+m.rows.length,0)+' applicable rows.');
