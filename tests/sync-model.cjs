const assert=require('node:assert/strict');
const S=require('../js/sync-model.js');
const empty=()=>({vehicles:[],services:[],settings:{}});
const base={vehicles:[{id:'car',mileage:100}],services:[],settings:{}};
const left=S.clone(base),right=S.clone(base);
left.services.push({id:'a',vehicleId:'car',price:200});
right.services.push({id:'b',vehicleId:'car',price:300});
assert.equal(S.merge(base,left,right).data.services.length,2);
assert.deepEqual(S.merge(base,left,right).conflicts,[]);
left.vehicles[0].mileage=101;right.vehicles[0].mileage=102;
assert.equal(S.merge(base,left,right).conflicts.length,1);
assert.equal(S.merge(base,empty(),right).conflicts.length>0,true);
const deleteVsService=S.merge(base,empty(),{...base,services:[{id:'s',vehicleId:'car'}]});
assert.ok(deleteVsService.conflicts.includes('references'));
assert.deepEqual(S.merge(base,left,left).data,left);
assert.deepEqual(S.merge(left,left,base).data,base);
assert.deepEqual(S.merge(base,empty(),base).data,empty());
assert.throws(()=>S.validate({vehicles:[{id:'x'},{id:'x'}],services:[],settings:{}}));
assert.throws(()=>S.validate({vehicles:[],services:[{id:'s',vehicleId:'x'}],settings:{}}));
assert.ok(S.equal({a:1,b:2},{b:2,a:1}));
console.log('Three-way merge: independent changes, conflicting edits/deletes, idempotency, references and ID validation passed.');
